// Builds one shared SVG sprite for every lucide icon the storefront uses, plus the React wrappers that reference it.
//   node scripts/icons/make-sprite.mjs
// Why: inline lucide icons repeat ~450 bytes of SVG markup per use (a third of the HTML on some pages). A <use> reference is ~100 bytes
// and the sprite is downloaded once and cached. The wrapper is server-safe and takes the same className prop.
//
// TrustpilotWidget.tsx is deliberately left on lucide-react (review widgets are not touched).
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { createElement } from 'react';
import { renderToStaticMarkup } from 'react-dom/server';
import * as lucide from 'lucide-react';

const ROOT = process.cwd();
const SRC = path.join(ROOT, 'src');
const SKIP = new Set([path.join(SRC, 'components', 'TrustpilotWidget.tsx')]);

function walk(dir, out = []) {
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, e.name);
    if (e.isDirectory()) walk(p, out);
    else if (/\.(tsx|ts)$/.test(e.name)) out.push(p);
  }
  return out;
}

const names = new Set();
for (const file of walk(SRC)) {
  if (SKIP.has(file) || file.endsWith(path.join('components', 'icons.tsx'))) continue;
  const text = fs.readFileSync(file, 'utf8');
  for (const m of text.matchAll(/import\s*\{([^}]*)\}\s*from\s*['"](?:lucide-react|@\/components\/icons)['"]/g)) {
    for (const n of m[1].split(',').map((s) => s.trim()).filter(Boolean)) names.add(n);
  }
}

const kebab = (n) => n.replace(/([a-z0-9])([A-Z])/g, '$1-$2').replace(/([a-zA-Z])(\d)/g, '$1-$2').toLowerCase();
const symbols = [];
for (const name of [...names].sort()) {
  const Icon = lucide[name];
  if (!Icon) throw new Error(`lucide-react has no icon called ${name}`);
  const svg = renderToStaticMarkup(createElement(Icon));
  const inner = svg.replace(/^<svg[^>]*>/, '').replace(/<\/svg>$/, '');
  symbols.push({ name, id: kebab(name), inner });
}

const sprite = `<svg xmlns="http://www.w3.org/2000/svg">${symbols.map((s) => `<symbol id="${s.id}" viewBox="0 0 24 24">${s.inner}</symbol>`).join('')}</svg>\n`;
const hash = crypto.createHash('sha1').update(sprite).digest('hex').slice(0, 8);
const file = `icons.${hash}.svg`;

const pub = path.join(ROOT, 'public');
for (const f of fs.readdirSync(pub)) if (/^icons\.[0-9a-f]{8}\.svg$/.test(f) && f !== file) fs.unlinkSync(path.join(pub, f));
fs.writeFileSync(path.join(pub, file), sprite);

const component = `// GENERATED by scripts/icons/make-sprite.mjs. Do not edit by hand.
// Same icons as lucide-react, drawn from one cached sprite instead of repeating the SVG inline on every use.
import type { AriaAttributes } from 'react';

const SPRITE = '/${file}';

type IconProps = { className?: string } & Pick<AriaAttributes, 'aria-hidden' | 'aria-label'>;

const icon = (id: string) =>
  function Icon({ className, ...rest }: IconProps) {
    return (
      <svg className={className ? \`ic \${className}\` : 'ic'} viewBox="0 0 24 24" aria-hidden="true" {...rest}>
        <use href={\`\${SPRITE}#\${id}\`} />
      </svg>
    );
  };

${symbols.map((s) => `export const ${s.name} = icon('${s.id}');`).join('\n')}
`;
fs.writeFileSync(path.join(SRC, 'components', 'icons.tsx'), component);
console.log(`sprite ${file}: ${symbols.length} icons, ${sprite.length} bytes`);
