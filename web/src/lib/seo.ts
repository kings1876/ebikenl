import type { Metadata } from 'next';
import { withLocale } from '@/i18n/config';
import type { Locale } from '@/i18n/config';
import { translate } from '@/i18n/translate';

type PageMetaOptions = {
  /** Dutch source title (translated for English). Use `absoluteTitle` to skip the site suffix. */
  title: string;
  absoluteTitle?: boolean;
  description?: string;
  noindex?: boolean;
  images?: string[];
};

export const tx = (locale: Locale, text: string) => translate(locale, text) as string;

export const SITE_URL = process.env.NEXT_PUBLIC_SITE_URL ?? 'https://e-bike-tekoop.nl';
export const SITE_NAME = 'E-BIKE-TEKOOP.NL';
// Default share image (generated by scripts/brand/make-icons.mjs, served from src/app/opengraph-image.png)
const DEFAULT_OG_IMAGE = { url: `${SITE_URL}/opengraph-image.png`, width: 1200, height: 630, alt: SITE_NAME };

export function pageMeta(locale: Locale, path: string, o: PageMetaOptions): Metadata {
  const title = tx(locale, o.title);
  return {
    title: o.absoluteTitle ? { absolute: title } : title,
    ...(o.description ? { description: tx(locale, o.description) } : {}),
    alternates: {
      canonical: withLocale(path, locale),
      languages: {
        'nl-NL': path,
        en: withLocale(path, 'en'),
        'x-default': path,
      },
    },
    openGraph: {
      type: 'website' as const,
      siteName: SITE_NAME,
      locale: locale === 'en' ? 'en_US' : 'nl_NL',
      url: withLocale(path, locale),
      images: o.images ?? [DEFAULT_OG_IMAGE],
    },
    twitter: {
      card: 'summary_large_image' as const,
      images: o.images ?? [DEFAULT_OG_IMAGE.url],
    },
    ...(o.noindex ? { robots: { index: false, follow: o.noindex === true } } : {}),
  };
}

